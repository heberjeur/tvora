    fun formatGenreList(genres: List<String>, targetLocale: Locale): String {
        if (genres.isEmpty()) return ""
        if (targetLocale.language.equals("fr", ignoreCase = true)) {
            return genres.joinToString(", ")
        }
        return genres.map { formatCategory(it, targetLocale) }.distinct().joinToString(", ")
    }
